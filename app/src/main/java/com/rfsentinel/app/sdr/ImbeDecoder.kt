/**
 * P25 voice, third step: the IMBE 4400 vocoder, from a codeword's 88 info bits ([P25Voice.Imbe]) to 20 ms of speech,
 * 160 samples at 8 kHz. One decoder per call: each codeword's spectrum is coded against the one before it.
 * A port of mbelib (ISC licence, after TIA-102.BABA): its decoding, spectral enhancement and synthesis, its tables;
 * a damaged codeword repeats the last good one, up to three times, then the call goes silent.
 */
class ImbeDecoder(rnd: Random = Random(1)) : MbeSynth(rnd) {

    /** 20 ms of speech from one codeword; [errors]: the bits its error correction fixed. */
    fun decode(bits: ByteArray, errors: Int): ShortArray = speak(parms(bits) && errors <= 5)

    /** The codeword's bits to [cur]; false when they hold no speech (silence, or not valid). */
    private fun parms(d: ByteArray): Boolean {
        cur.repeat = prev.repeat
        var b0 = 0
        for (i in intArrayOf(0, 1, 2, 3, 4, 5, 85, 86)) b0 = b0 shl 1 or d[i].toInt()
        if (b0 > 207) return false
        val w0 = 4 * PI / (b0 + 39.5)
        val L = (0.9254 * (PI / w0 + 0.25).toInt()).toInt()
        if (L !in 9..56) return false
        cur.w0 = w0; cur.L = L
        val L9 = L - 9
        val K = if (L < 37) (L + 2) / 3 else 12

        // The info bits, priority ordered, back to b_m (bit k of each).
        val bb = Array(58) { IntArray(12) }
        for (i in 6 until 85) { val p = L9 * 79 + i - 6; bb[BO_M[p] - '0'][BO_B[p] - '0'] = d[i].toInt() }
        fun value(m: Int, bits: Int): Int { var v = 0; for (x in bits - 1 downTo 0) v = v shl 1 or bb[m][x]; return v }

        // Voicing: one bit per three harmonics.
        var j = 1; var k = K - 1
        for (l in 1..L) {
            cur.Vl[l] = bb[1][k]
            if (j == 3) { j = 1; if (k > 0) k-- } else j++
        }

        // Gains G1..G6, inverse DCT to the block averages R1..R6.
        val g = DoubleArray(7)
        g[1] = B2[value(2, 6)].toDouble()
        for (i in 2..6) {
            val bits = BA[L9 * 10 + 2 * (i - 2)].toInt(); val step = BA[L9 * 10 + 2 * (i - 2) + 1].toDouble()
            g[i] = step * (value(i + 1, bits) - 2.0.pow(bits - 1) + 0.5)
        }
        // Each block: its average and higher order DCT coefficients, inverse DCT to its share of the L residuals.
        val t = DoubleArray(SLOTS)
        var m = 8; var l = 1
        for (i in 1..6) {
            var r = 0.0
            for (n in 1..6) r += (if (n == 1) 1 else 2) * g[n] * cos(PI * (n - 1) * (i - 0.5) / 6)
            val ji = L / 6 + if (i > 6 - L % 6) 1 else 0
            val c = DoubleArray(ji + 1)
            c[1] = r
            for (kk in 2..ji) {
                val bm = HOBA[L9 * 50 + m - 8] - '0'
                c[kk] = if (bm == 0) 0.0 else QUANT_STEP[bm - 1] * STAND_DEV[kk - 2] * (value(m, bm) - 2.0.pow(bm - 1) + 0.5)
                m++
            }
            for (jj in 1..ji) {
                var s = 0.0
                for (kk in 1..ji) s += (if (kk == 1) 1 else 2) * c[kk] * cos(PI * (kk - 1) * (jj - 0.5) / ji)
                t[l++] = s
            }
        }

        // The residuals add to the previous spectrum, resampled to L harmonics.
        val rho = when { L <= 15 -> 0.4; L <= 24 -> 0.03 * L - 0.05; else -> 0.7 }
        if (L > prev.L) for (x in prev.L + 1..L) { prev.Ml[x] = prev.Ml[prev.L]; prev.log2Ml[x] = prev.log2Ml[prev.L] }
        val kl = IntArray(L + 1); val dl = DoubleArray(L + 1)
        var sum = 0.0
        for (x in 1..L) {
            val f = prev.L.toDouble() / L * x
            kl[x] = f.toInt(); dl[x] = f - kl[x]
            sum += (1 - dl[x]) * prev.log2Ml[kl[x]] + dl[x] * prev.log2Ml[kl[x] + 1]
        }
        sum *= rho / L
        for (x in 1..L) {
            cur.log2Ml[x] = t[x] + rho * (1 - dl[x]) * prev.log2Ml[kl[x]] + rho * dl[x] * prev.log2Ml[kl[x] + 1] - sum
            cur.Ml[x] = 2.0.pow(cur.log2Ml[x])
        }
        return true
    }

