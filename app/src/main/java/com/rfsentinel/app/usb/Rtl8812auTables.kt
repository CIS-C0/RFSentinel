    private const val RFE_INV_MASK = 0x3FF00000

    /**
     * The RFE pins (phy_SetRFEReg8812): which antenna switch / LNA / PA lines the baseband drives, by the board's
     * RFE type (read from the adapter's efuse), for 2.4 or 5 GHz. A type that is not listed leaves the pins alone.
     */
    fun rfePins(rfe: Int, ghz5: Boolean): Array<IntArray> {
        fun pin(v: Int, inv: Int) = arrayOf(
            intArrayOf(BB, RFE_PINMUX_A, -1, v), intArrayOf(BB, RFE_PINMUX_B, -1, v),
            intArrayOf(BB, RFE_INV_A, RFE_INV_MASK, inv), intArrayOf(BB, RFE_INV_B, RFE_INV_MASK, inv))
        return if (!ghz5) when (rfe) {
            0, 1, 2 -> pin(0x77777777, 0x000)
            3 -> pin(0x54337770, 0x010) + intArrayOf(BB, 0x900, 0x303, 0x1)
            4 -> pin(0x77777777, 0x001)
            5 -> arrayOf(intArrayOf(BB, RFE_PINMUX_A, 0x00FF0000, 0x77), intArrayOf(BB, RFE_PINMUX_B, -1, 0x77777777),
                intArrayOf(BB, RFE_INV_A, 0x01000000, 0x0), intArrayOf(BB, RFE_INV_B, RFE_INV_MASK, 0x000))
            6 -> arrayOf(intArrayOf(BB, RFE_PINMUX_A, -1, 0x07772770), intArrayOf(BB, RFE_PINMUX_B, -1, 0x07772770),
                intArrayOf(BB, RFE_INV_A, -1, 0x77), intArrayOf(BB, RFE_INV_B, -1, 0x77))
            else -> emptyArray()
        } else when (rfe) {
            0 -> pin(0x77337717, 0x010)
            1 -> pin(0x77337717, 0x000)
            2, 4 -> pin(0x77337777, 0x010)
            3 -> pin(0x54337717, 0x010) + intArrayOf(BB, 0x900, 0x303, 0x1)
            5 -> arrayOf(intArrayOf(BB, RFE_PINMUX_A, 0x00FF0000, 0x33), intArrayOf(BB, RFE_PINMUX_B, -1, 0x77337777),
                intArrayOf(BB, RFE_INV_A, 0x01000000, 0x1), intArrayOf(BB, RFE_INV_B, RFE_INV_MASK, 0x010))
            6 -> arrayOf(intArrayOf(BB, RFE_PINMUX_A, -1, 0x07737717), intArrayOf(BB, RFE_PINMUX_B, -1, 0x07737717),
                intArrayOf(BB, RFE_INV_A, -1, 0x77), intArrayOf(BB, RFE_INV_B, -1, 0x77))
            else -> emptyArray()
        }
    }

    /**
     * Tunes to [ch] at 20 MHz, receive only: the band switch (PHY_SwitchWirelessBand8812), the sub-band and channel
     * for both radio paths (phy_SwChnl8812) and the 20 MHz bandwidth (phy_PostSetBwMode8812, PHY_RF6052SetBandwidth8812).
     * [cut] is the chip's revision (0 = A, 1 = B, 2 = C...): the C cut has its own spur fix.
     */
    fun channelTune(ch: Int, rfe: Int, cut: Int): Array<IntArray> {
        val g5 = ch > 14
        val band: Array<IntArray> = if (!g5) arrayOf(
            intArrayOf(BB, 0x808, 0x30000000, 0x3),
            intArrayOf(BB, 0x834, 0x3, 0x1),
            intArrayOf(BB, 0x830, 0x3E000, 0x17),
            intArrayOf(BB, 0x830, 0xE, 0x4),
            intArrayOf(BB, 0x82C, 0x3, 0x0)
        ) + rfePins(rfe, false) + arrayOf(
            intArrayOf(BB, 0x80C, 0xF0, 0x1),
            intArrayOf(BB, 0xA04, 0x0F000000, 0x1),
            intArrayOf(MAC8, 0x454, 0x80, 0x0)
        ) else arrayOf(
            intArrayOf(MAC8, 0x454, 0x80, 0x1),
            intArrayOf(BB, 0x808, 0x30000000, 0x3),
            intArrayOf(BB, 0x834, 0x3, 0x2),
            intArrayOf(BB, 0x830, 0x3E000, 0x15),
            intArrayOf(BB, 0x830, 0xE, 0x4),
            intArrayOf(BB, 0x82C, 0x3, 0x1)
        ) + rfePins(rfe, true) + arrayOf(
            intArrayOf(BB, 0x80C, 0xF0, 0x0),
            intArrayOf(BB, 0xA04, 0x0F000000, 0xF)
        )
        val fc = when { ch in 15..48 -> 0x494; ch in 50..80 -> 0x453; ch in 82..116 -> 0x452; ch >= 118 -> 0x412; else -> 0x96A }
        val mod = when { ch in 15..80 -> 0x101; ch in 82..140 -> 0x301; ch > 140 -> 0x501; else -> 0x0 }
        val chan = arrayOf(intArrayOf(BB, 0x860, 0x1FFE0000, fc)) + fixSpur(ch, cut) +
            arrayOf(intArrayOf(RF, 0x18, 0x70300, mod), intArrayOf(RFB, 0x18, 0x70300, mod)) +
            arrayOf(intArrayOf(RF, 0x18, 0xFF, ch), intArrayOf(RFB, 0x18, 0xFF, ch))
        val bw20 = arrayOf(
            intArrayOf(MAC16, 0x668, 0x180, 0x0),
            intArrayOf(MAC8, 0x483, 0xFF, 0x0),
            intArrayOf(BB, 0x8AC, 0x3003C3, 0x300200),
            intArrayOf(BB, 0x8C4, 0x40000000, 0x0),
            intArrayOf(BB, 0x848, 0x3C00000, 0x7)
        ) + fixSpur(ch, cut) + arrayOf(intArrayOf(RF, 0x18, 0xC00, 0x3), intArrayOf(RFB, 0x18, 0xC00, 0x3))
        return band + chan + bw20
    }

    /** phy_FixSpur_8812A at 20 MHz: the ADC clock for the 2.4 GHz spurs (the C cut and later also set the FIFO clock). */
    private fun fixSpur(ch: Int, cut: Int): Array<IntArray> {
        val top = ch == 13 || ch == 14
        return if (cut >= 2) arrayOf(
            intArrayOf(BB, 0x8AC, 0xC00, 0x2),
            intArrayOf(BB, 0x8AC, 0x300, if (top) 0x3 else 0x2),
            intArrayOf(BB, 0x8C4, 0x40000000, if (top) 0x1 else 0x0)
        ) else if (ch <= 14) arrayOf(intArrayOf(BB, 0x8AC, 0x300, if (top) 0x3 else 0x2)) else emptyArray()
    }

